        internal const string Header="// <auto-generated Wulato.UIKit T9>\n";
        const string Manifest=Root+"/manifest.json",Pending="Library/Wulato.UIKit.codegen.pending.json";
        static readonly string[] Keywords={"class","namespace","public","private","protected","internal","void","int","string","object","event","base","this","new","return","null","true","false","ref","out","in","params","partial","static","readonly","const","struct","interface","enum","delegate","using","default","operator","is","as","var","if","else","while","for","foreach","switch","case","break","continue","throw","try","catch","finally","override","virtual","abstract","sealed","async","await","get","set","value","bool","byte","char","double","float","long","short","uint","ulong","ushort","sbyte","decimal","checked","unchecked","do","goto","fixed","unsafe","stackalloc","lock","sizeof","typeof","volatile","extern","implicit","explicit"};
        internal static bool Identifier(string name)=>!string.IsNullOrEmpty(name)&&Regex.IsMatch(name,"^[A-Za-z_][A-Za-z0-9_]*$")&&!Keywords.Contains(name);
        internal static string TypeName(Type t)
        {
            if(t.IsArray)return TypeName(t.GetElementType())+"[]";
            if(t.IsGenericType)return "global::"+t.GetGenericTypeDefinition().FullName.Split('`')[0].Replace('+','.')+"<"+string.Join(",",t.GetGenericArguments().Select(TypeName))+">";
            return "global::"+t.FullName.Replace('+','.');
        }
        internal static string Literal(string text)=>"\""+text.Replace("\\","\\\\").Replace("\"","\\\"").Replace("\r","\\r").Replace("\n","\\n")+"\"";
        internal static string Hash(string text){using(var sha=SHA256.Create())return BitConverter.ToString(sha.ComputeHash(Encoding.UTF8.GetBytes(text))).Replace("-","").ToLowerInvariant();}
        internal static string ProviderName(UIBindingRoute route)=>"UIProvider_"+Hash(route.AsmdefGuid+route.Assembly).Substring(0,16);
        static string[] Discover()
        {
            var runtimeAssemblies=new HashSet<string>(UnityEditor.Compilation.CompilationPipeline.GetAssemblies(UnityEditor.Compilation.AssembliesType.Player).Where(a=>(a.flags&UnityEditor.Compilation.AssemblyFlags.EditorAssembly)==0).Select(a=>a.name));
            return AssetDatabase.FindAssets("t:Prefab",new[]{"Assets"}).Select(AssetDatabase.GUIDToAssetPath).Where(path=>
            {
                var marker=AssetDatabase.LoadAssetAtPath<GameObject>(path).GetComponent<UIBindingMarker>();
                if(marker==null || !marker.includeInRegistry)return false;
                var script=marker.viewScript as MonoScript;var type=script==null?null:script.GetClass();
                // Broken authoring inputs must fail validation; known Editor-only Views are excluded.
                return type==null || runtimeAssemblies.Contains(type.Assembly.GetName().Name);
            }).OrderBy(path=>path,StringComparer.Ordinal).ToArray();
        }
        static string ObjectId(UnityEngine.Object obj)
        {
            if(!AssetDatabase.TryGetGUIDAndLocalFileIdentifier(obj,out string guid,out long id))throw new InvalidOperationException("Binding target must be a saved prefab component.");
            return guid+":"+id;
        }
        internal static bool ConflictsWithMember(string source,string fieldName)=>Regex.IsMatch(source,@"\b(?!(?:return|throw|yield|await)\b)(?:[A-Za-z_][\w:.]*)(?:\s*<[^;{}]+>)?(?:\[\])?\s+"+Regex.Escape(fieldName)+@"\s*(?:[;={])");
        static ViewInput[] Inputs(string[] paths)
        {
            var results=new List<ViewInput>();var types=new HashSet<Type>();var keys=new HashSet<string>(StringComparer.Ordinal);
            foreach(var path in paths.OrderBy(p=>p,StringComparer.Ordinal))
            {
                try
                {
                    var prefab=AssetDatabase.LoadAssetAtPath<GameObject>(path);
                    if(prefab==null)throw new InvalidOperationException("Missing Prefab.");
                    var marker=prefab.GetComponent<UIBindingMarker>();
                    if(marker==null || prefab.GetComponentsInChildren<UIBindingMarker>(true).Length!=1)throw new InvalidOperationException("Exactly one root marker is required.");
                    var script=marker.viewScript as MonoScript;var type=script==null?null:script.GetClass();
                    if(type==null || !typeof(UIViewBase).IsAssignableFrom(type) || type.IsAbstract || type.IsGenericType || type.IsNested)throw new InvalidOperationException("A concrete, top-level UIView partial script is required.");
                    var scriptPath=AssetDatabase.GetAssetPath(script);var source=File.ReadAllText(scriptPath);
                    if(!Regex.IsMatch(source,@"\bpartial\s+class\s+"+Regex.Escape(type.Name)+@"\b"))throw new InvalidOperationException("Business View must be partial; existing scripts are never edited.");
                    var guid=AssetDatabase.AssetPathToGUID(scriptPath);var route=UIBindingAssemblyRouter.Resolve(scriptPath);
                    var key=string.IsNullOrEmpty(marker.typeKey)?guid:marker.typeKey;
                    if(!types.Add(type)||!keys.Add(key))throw new InvalidOperationException("Duplicate View type or key.");
                    if(!(prefab.transform is RectTransform)||!prefab.activeSelf)throw new InvalidOperationException("Prefab requires active RectTransform root.");
                    var views=prefab.GetComponents<UIViewBase>();
                    if(views.Length>1 || (views.Length==1 && (views[0].GetType()!=type || !views[0].enabled)))throw new InvalidOperationException("Wrong, disabled or duplicate root View component.");
                    if(prefab.GetComponentsInChildren<Canvas>(true).Any(c=>c.overrideSorting) || prefab.GetComponentsInChildren<CanvasGroup>(true).Any(c=>c.ignoreParentGroups))throw new InvalidOperationException("Canvas/CanvasGroup bypasses Shell gates.");
                    if(!Enum.IsDefined(typeof(UILayer),marker.layer)||!Enum.IsDefined(typeof(UIMultiplicity),marker.multiplicity)||!Enum.IsDefined(typeof(UIClosePolicy),marker.closePolicy)||!Enum.IsDefined(typeof(UIBackAction),marker.backAction)||marker.multiplicity==UIMultiplicity.Multi&&marker.closePolicy==UIClosePolicy.CacheOne)throw new InvalidOperationException("Invalid registration policy.");
                    if(!string.IsNullOrEmpty(marker.externalProviderId) || !string.IsNullOrEmpty(marker.externalAssetId))
                        UIViewAsset.External(marker.externalProviderId,marker.externalAssetId);
                    var names=new HashSet<string>(StringComparer.Ordinal);var identity=new StringBuilder("T9-v1|"+guid+"|"+route.Assembly+"|"+route.AsmdefGuid+"|"+source+"|"+key+"|"+(int)marker.layer+"|"+(int)marker.multiplicity+"|"+(int)marker.closePolicy+"|"+(int)marker.backAction);
                    identity.Append('|').Append(AssetDatabase.AssetPathToGUID(path));
                    identity.Append('|').Append(marker.externalProviderId).Append('|').Append(marker.externalAssetId);
                    if(route.AsmdefGuid!="")identity.Append(File.ReadAllText(AssetDatabase.GUIDToAssetPath(route.AsmdefGuid)));
                    foreach(var binding in marker.bindings??throw new InvalidOperationException("Bindings list missing."))
                    {
                        if(!Identifier(binding.fieldName)||!names.Add(binding.fieldName))throw new InvalidOperationException("Invalid or duplicate binding field: "+binding.fieldName);
                        if(binding.target==null || !(binding.target.transform==prefab.transform || binding.target.transform.IsChildOf(prefab.transform)))throw new InvalidOperationException("Missing or cross-prefab reference: "+binding.fieldName);
                        if(binding.target.GetType().IsGenericType || !binding.target.GetType().IsVisible)throw new InvalidOperationException("Binding component must have a visible concrete type.");
                        // User/inherited members may not be silently hidden by a generated field.
                        if(ConflictsWithMember(source,binding.fieldName) || type.BaseType.GetMember(binding.fieldName,BindingFlags.Instance|BindingFlags.Public|BindingFlags.NonPublic).Length>0)throw new InvalidOperationException("Binding conflicts with business member: "+binding.fieldName);
                        identity.Append('|').Append(binding.fieldName).Append('|').Append(TypeName(binding.target.GetType())).Append('|').Append(ObjectId(binding.target));
                    }
                    Type args=null;var branch=type;
                    while(branch!=null){if(branch.IsGenericType&&branch.GetGenericTypeDefinition()==typeof(UIView<>)){args=branch.GetGenericArguments()[0];break;}branch=branch.BaseType;}
                    if(args==null&&!typeof(UIView).IsAssignableFrom(type))throw new InvalidOperationException("Unsupported UIView branch.");
                    results.Add(new ViewInput{Path=path,Prefab=prefab,Marker=marker,Type=type,Args=args,Guid=guid,Key=key,Route=route,Fingerprint=Hash(identity.ToString())});
                }
                catch(Exception error){throw new InvalidOperationException(path+": "+error.Message,error);}
            }
            return results.ToArray();
        }
        static SortedDictionary<string,string> Sources(ViewInput[] views)
        {
            var files=new SortedDictionary<string,string>(StringComparer.Ordinal);
            foreach(var view in views)files.Add(view.Route.Directory+"/"+view.Guid+".Bindings.cs",UIBindingGenerator.Generate(view));
            foreach(var group in views.GroupBy(v=>v.Route.Directory))
            {
                var route=group.First().Route;UIBindingAssemblyRouter.ValidateLayout(route);
                if(route.AsmdefGuid!="")files.Add(route.Directory+"/Assembly.asmref","{\"reference\":\"GUID:"+route.AsmdefGuid+"\"}\n");
                files.Add(route.Directory+"/"+ProviderName(route)+".cs",UIRegistryProviderGenerator.Generate(group.ToArray(),ProviderName(route)));
            }
            return files;
        }
        public static string Preview(string[] prefabs)=>string.Join("\n",Sources(Inputs(prefabs)).Select(p=>p.Key+"\n"+p.Value));
        static CodegenState State(ViewInput[] views,SortedDictionary<string,string> files)=>new CodegenState{prefabs=views.Select(v=>v.Path).ToArray(),fingerprint=Hash(string.Join("|",views.Select(v=>v.Fingerprint))),files=files.Select(f=>new GeneratedFile{path=f.Key,hash=Hash(f.Value)}).ToArray()};
        static void WriteIfChanged(string path,string text){if(File.Exists(path)&&File.ReadAllText(path)==text)return;Directory.CreateDirectory(Path.GetDirectoryName(path));File.WriteAllText(path,text);}
        [MenuItem("Tools/Wulato/UIKit/Generate")]
        public static void Generate()=>GenerateFor(Discover());
        public static void GenerateFor(string[] prefabs)
        {
            var views=Inputs(prefabs);var files=Sources(views);var state=State(views,files);
            bool compileChanged=files.Any(file=>!File.Exists(file.Key)||File.ReadAllText(file.Key)!=file.Value);
            if(File.Exists(Manifest))
            {
                var previous=JsonUtility.FromJson<CodegenState>(File.ReadAllText(Manifest));
                foreach(var old in previous.files)
                {
                    if(files.ContainsKey(old.path))continue;
                    compileChanged=true;
                    if(!old.path.StartsWith(Root+"/",StringComparison.Ordinal)||old.path.Contains(".."))throw new InvalidOperationException("Invalid owned file path: "+old.path);
                    if(File.Exists(old.path)&&Hash(File.ReadAllText(old.path))!=old.hash)throw new InvalidOperationException(old.path+": Owned file was modified; refusing removal.");
                    if(old.path.EndsWith(".cs") && Path.GetFileName(old.path).StartsWith("UIProvider_"))AssetDatabase.DeleteAsset(Path.ChangeExtension(old.path,".asset"));
                    AssetDatabase.DeleteAsset(old.path);
                }
            }
            foreach(var file in files)
            {
                if(File.Exists(file.Key)&&!File.ReadAllText(file.Key).StartsWith(Header,StringComparison.Ordinal)&&!file.Key.EndsWith(".asmref"))throw new InvalidOperationException(file.Key+": Refusing to overwrite user file.");
                WriteIfChanged(file.Key,file.Value);
            }
            WriteIfChanged(Manifest,JsonUtility.ToJson(state,true)+"\n");WriteIfChanged(Pending,JsonUtility.ToJson(state,true)+"\n");AssetDatabase.Refresh();
            if(!compileChanged && !EditorApplication.isCompiling)Complete();
        }
        [MenuItem("Tools/Wulato/UIKit/Complete writeback")]
        public static void Complete()
        {
            if(!File.Exists(Pending))return;
            if(EditorApplication.isCompiling)throw new InvalidOperationException("Wait for generated scripts to compile before writeback.");
            var state=JsonUtility.FromJson<CodegenState>(File.ReadAllText(Pending));var views=Inputs(state.prefabs);
            if(State(views,Sources(views)).fingerprint!=state.fingerprint)throw new InvalidOperationException("Codegen inputs changed before writeback; generate again.");
            foreach(var v in views)
            {
                UIBindingAssemblyRouter.Validate(v.Route.Directory+"/"+v.Guid+".Bindings.cs",v.Route);
                UIBindingAssemblyRouter.Validate(v.Route.Directory+"/"+ProviderName(v.Route)+".cs",v.Route);
                UIBindingWriteback.Apply(v);
            }
            UIRegistryGenerator.Write(views);AssetDatabase.SaveAssets();File.Delete(Pending);
        }
        [DidReloadScripts] static void Resume()
        {
            if(Application.isBatchMode||!File.Exists(Pending))return;
            EditorApplication.delayCall+=()=>{try{Complete();}catch(Exception e){Debug.LogException(e);}};
        }
        static bool AssetMatches(UIViewAsset asset,ViewInput view)
        {
            return string.IsNullOrEmpty(view.Marker.externalProviderId)
                ? asset.Kind==UIViewAssetKind.Prefab && asset.Prefab==view.Prefab
                : asset.Kind==UIViewAssetKind.External && asset.ProviderId==view.Marker.externalProviderId && asset.AssetId==view.Marker.externalAssetId;
        }
        [MenuItem("Tools/Wulato/UIKit/Validate")]
        public static void Validate()=>ValidateFor(Discover());
        public static void ValidateFor(string[] prefabs)
        {
            var views=Inputs(prefabs);var files=Sources(views);var state=State(views,files);
            if(File.Exists(Pending)||!File.Exists(Manifest))throw new InvalidOperationException("Bindings missing or pending; generate, compile and complete writeback before build.");
            var prior=JsonUtility.FromJson<CodegenState>(File.ReadAllText(Manifest));
            if(prior.fingerprint!=state.fingerprint || prior.files.Length!=state.files.Length)throw new InvalidOperationException("Stale fingerprint: regenerate bindings and registry.");
            foreach(var f in state.files)
            {
                if(!File.Exists(f.path)||Hash(File.ReadAllText(f.path))!=f.hash)throw new InvalidOperationException(f.path+": Stale or missing generated file.");
            }
            foreach(var v in views)
            {
                UIBindingAssemblyRouter.Validate(v.Route.Directory+"/"+v.Guid+".Bindings.cs",v.Route);
                UIBindingAssemblyRouter.Validate(v.Route.Directory+"/"+ProviderName(v.Route)+".cs",v.Route);
                var view=v.Prefab.GetComponent(v.Type);
                if(view==null)throw new InvalidOperationException(v.Path+": Missing generated View component.");
                var so=new SerializedObject(view);
                foreach(var b in v.Marker.bindings)
                    if(so.FindProperty(b.fieldName)?.objectReferenceValue!=b.target)throw new InvalidOperationException(v.Path+": Missing/stale serialized binding "+b.fieldName);
            }
            var registry=AssetDatabase.LoadAssetAtPath<UIRegistry>(RegistryPath);
            if(registry==null)throw new InvalidOperationException(RegistryPath+": Missing registry.");
            var entries=registry.CopyValidated().Entries;
            if(entries.Count!=views.Length || views.Any(v=>!entries.Any(e=>e.ViewType==v.Type&&e.Key.Value==v.Key&&AssetMatches(e.Asset,v)&&e.Layer==v.Marker.layer&&e.Multiplicity==v.Marker.multiplicity&&e.ClosePolicy==v.Marker.closePolicy&&e.BackAction==v.Marker.backAction)))throw new InvalidOperationException(RegistryPath+": Stale generated provider mappings.");
        }
